// Фон был одним вертикальным градиентом плюс три размытых пятна. На экране это
// читалось как ровная серая заливка: ни глубины, ни фактуры, ни повода
// смотреть. Именно отсюда ощущение «дешёво по сравнению с остальным
// приложением» — не от цвета кнопок, а от того, что за формой ПУСТО. У Netflix
// за формой входа сетка кадров: она даёт глубину и говорит «здесь кино»
// до того, как человек прочтёт хоть слово.
//
// ЧТО ЗДЕСЬ ТЕПЕРЬ
//
// Шесть слоёв вместо одного (порядок важен):
//
//   1. База — ТЁПЛЫЙ почти чёрный, не #000. Чистый чёрный на OLED даёт
//      провал, в котором не работает ни одна тень, и любой градиент поверх
//      выглядит грязным. Тёплый уголь оставляет запас на четыре ступени
//      подъёма для полей и кнопок.
//   2. Стена афиш — НАСТОЯЩИЕ постеры кино 1925–1929 (общественное
//      достояние), приведённые к тёплому монотону шелла.
//   3. Луч проектора — из-за верхней кромки, к знаку. Мотивирует свет:
//      знак светится, потому что на него падает луч.
//   4. Виньетка — круговая, гасит углы, собирает взгляд в центр.
//   5. Скрим под формой — гарантия контраста независимо от того, что
//      происходит в слоях выше.
//   6. Зерно плёнки — то, что отличает «кино» от «градиента». Без него
//      любой тёмный фон выглядит пластиковым баннером.
//
// ПОЧЕМУ АФИШИ НАСТОЯЩИЕ, А НЕ НАРИСОВАННЫЕ (правка 04.08.2026)
//
// Слой 2 переделывали трижды.
//
//   1. Наклонённая сетка «постеров» — одинаковые прямоугольники 2:3 со сдвигом
//      ряда на половину ширины. Прочли как КИРПИЧНУЮ КЛАДКУ, и правильно: ряды
//      одинаковых блоков со сдвигом на полблока — дословное определение
//      кирпичной перевязки. Ни приглушённые тона, ни размытие не помогали,
//      потому что дело было не в цвете, а в схеме раскладки: постер узнаётся по
//      СОДЕРЖИМОМУ, а содержимого в генерации нет.
//   2. Нарисованный кодом зал с креслами. Кладку убрал, но кресла читались
//      дешёвой машинной графикой: сколько ни добавляй разброса размеров и
//      яркости, нарисованное кресло остаётся нарисованным креслом.
//   3. Настоящие афиши (сейчас). Имитировать фотографию кодом было незачем —
//      ошибкой был не отказ от фотографии, а попытка подделать её.
//
// ПОЧЕМУ ЭТИ ПОСТЕРЫ БРАТЬ МОЖНО, А ПОСТЕРЫ NETFLIX — НЕЛЬЗЯ
//
// Все двенадцать афиш — американское кино 1925–1929 годов, опубликованное в США
// до 1930 года, то есть ОБЩЕСТВЕННОЕ ДОСТОЯНИЕ: срок охраны истёк, прав ни у
// одной студии не осталось. Полотно собирается из них на этапе сборки ассета
// (scripts/make_poster_wall.py, гейт по лицензии и году), в приложение попадает
// готовый файл — по сети в рантайме не загружается ничего.
//
// Прошлая версия тянула Dune и Oppenheimer с image.tmdb.org и оправдывалась
// тем, что «не бандлит»: это отвечает на вопрос о распространении, а не о праве
// показывать. App Review 5.2 требует, чтобы приложение подавала сторона,
// которой права принадлежат или лицензированы; Netflix показывает эти постеры,
// потому что лицензировал сам контент. Разница между теми постерами и этими не
// в том, «нарисовано или сфотографировано», а в том, истёк ли срок охраны.
//
// Перечень афиш с годами, лицензиями и ссылками — в ART_ASSET_LICENSES.md.
//
// Тона намеренно сняты до тёплого монотона: фон даёт ФАКТУРУ И ГЛУБИНУ, а не
