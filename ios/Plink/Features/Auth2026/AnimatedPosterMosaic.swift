/// Принудительное включение доступностных режимов для рендера кадров аудита.
///
/// `\.accessibilityReduceTransparency` и `\.accessibilityReduceMotion` в
/// SwiftUI доступны только на чтение: выставить их из теста нельзя, а
/// UIKit-трейтами эти два флага не переопределяются (пробовал
/// `accessibilityContrast = .high` — кадр выходил побайтово равен обычному,
/// то есть тест «проверял» ровно ничего).
///
/// Фон собран из шести слоёв, и каждый обязан гаситься по этим настройкам.
/// Ломается такой код молча: обычные кадры выглядят нормально, а человек с
/// включённой настройкой получает либо кашу, либо пустой чёрный экран.
/// Поэтому нужен шов, через который оба состояния реально снимаются.
struct PlinkAccessibilityOverride: Equatable {
    var reduceTransparency = false
    var reduceMotion = false
}

/// «Заморозить анимации» — для офскрин-рендера кадров аудита.
///
/// Отдельный ключ, а не `reduceMotion`: это НЕ настройка доступности, и
/// смешивать их нельзя. Кадр Reduce Transparency обязан сниматься с выключенным
/// Reduce Motion, иначе тест проверяет две настройки разом и не проверяет ни
/// одну толком.
///
/// Зачем вообще. Экран входа проявляется пружиной, а фон живёт вечной
/// анимацией. Офскрин-рендер ловил то середину проявления (кадр выглядел
/// регрессом: «кнопка потемнела»), то вовсе пустой экран. Попытка «снимать,
/// пока два кадра не совпадут» не помогла: из-за вечной анимации фона кадры не
/// сходятся никогда, а повторные `drawHierarchy` иногда отдают пустоту.
///
/// Поэтому анимации не пережидаются, а ВЫКЛЮЧАЮТСЯ: сцена сразу в конечном
/// состоянии, рендер один, результат детерминированный.
struct PlinkFreezeAnimationsKey: EnvironmentKey {
    static let defaultValue = false
}

extension EnvironmentValues {
    var plinkFreezeAnimations: Bool {
        get { self[PlinkFreezeAnimationsKey.self] }
        set { self[PlinkFreezeAnimationsKey.self] = newValue }
    }
}

private struct PlinkAccessibilityOverrideKey: EnvironmentKey {
    static let defaultValue = PlinkAccessibilityOverride()
}

extension EnvironmentValues {
    var plinkAccessibilityOverride: PlinkAccessibilityOverride {
        get { self[PlinkAccessibilityOverrideKey.self] }
        set { self[PlinkAccessibilityOverrideKey.self] = newValue }
    }
}

struct ProjectorBeamBackground: View {
    /// Фаза стены для снапшот-тестов. Значение произвольное — важно лишь то, что
    /// оно ФИКСИРОВАНО: при заморозке анимаций рендер обязан быть одинаковым от
    /// прогона к прогону, иначе тесты дизайна начинают ловить шум вместо
    /// регрессов.
    private static let frozenPhase: TimeInterval = 37

    @Environment(\.accessibilityReduceMotion) private var systemReduceMotion
    @Environment(\.accessibilityReduceTransparency) private var systemReduceTransparency
    @Environment(\.plinkAccessibilityOverride) private var override
    @Environment(\.plinkFreezeAnimations) private var freezeAnimations
    @Environment(\.scenePhase) private var scenePhase

    private var reduceMotion: Bool {
        systemReduceMotion || override.reduceMotion || freezeAnimations
    }
    private var reduceTransparency: Bool {
        systemReduceTransparency || override.reduceTransparency
    }

    private var animationEnabled: Bool {
        !reduceMotion
            && scenePhase == .active
            && !ProcessInfo.processInfo.isLowPowerModeEnabled
            && ProcessInfo.processInfo.thermalState == .nominal
    }

    var body: some View {
        GeometryReader { proxy in
            let size = proxy.size
            ZStack {
                // 1. База.
                LinearGradient(
                    stops: [
                        .init(color: PlinkTheatre.velvet, location: 0),
                        .init(color: PlinkTheatre.velvetDeep, location: 0.55),
                        .init(color: Color(hex: 0x08080A), location: 1),
                    ],
                    startPoint: .top,
                    endPoint: .bottom
                )

                if !reduceTransparency {
                    // 2. Стена афиш.
                    //
                    // Два разных случая «стена не движется», и путать их нельзя.
                    //
                    //   • Снапшот-тест (`plinkFreezeAnimations`) — нужен ОДИН И
                    //     ТОТ ЖЕ кадр при каждом прогоне, иначе рендер перестаёт
                    //     быть воспроизводимым побайтово и тесты дизайна начинают
                    //     ловить несуществующие регрессы. Отсюда фиксированное
                    //     `t`, взятое от фазы, а не от часов.
                    //   • Рантайм (уход в фон, Low Power, нагрев, Reduce Motion) —
                    //     нужен ОСТАНОВ ТАМ ЖЕ, где стена сейчас. Раньше здесь
                    //     тоже подставлялся фиксированный кадр, и стена при каждом
                    //     таком переключении ПРЫГАЛА: своя фаза против реального
                    //     времени, расхождение до 39 pt по горизонтали. Теперь
                    //     таймлайн один и тот же, он лишь ставится на паузу, так
                    //     что фаза сохраняется.
                    //
                    // 1/12 с достаточно: панорама идёт со скоростью порядка
                    // 0.26 pt/с (амплитуда 5% ширины, период ~8 мин), то есть
                    // смещение между кадрами — доли пикселя. Судить о плавности
                    // тут нечему, а перерисовка размытого полотна стоит дорого,
                    // поэтому чаще звать незачем.
                    if freezeAnimations {
                        PosterWall(size: size, t: Self.frozenPhase)
                    } else {
                        TimelineView(
                            .animation(minimumInterval: 1 / 12, paused: !animationEnabled)
                        ) { timeline in
                            PosterWall(
                                size: size,
                                t: timeline.date.timeIntervalSinceReferenceDate
                            )
                        }
                    }

                    // 3. Луч проектора.
                    ProjectorBeam(size: size)
                }

                // 4. Виньетка — всегда, в том числе при Reduce Transparency:
                // это не украшение, а то, что удерживает взгляд на форме.
                // Ослаблена вместе со скримом: два затемнения поверх насыщенной
                // стены складывались и оставляли от цвета серую муть.
                RadialGradient(
                    stops: [
                        .init(color: .clear, location: 0),
                        .init(color: .clear, location: 0.46),
                        .init(color: .black.opacity(0.20), location: 0.80),
                        .init(color: .black.opacity(0.48), location: 1),
                    ],
                    center: .center,
                    startRadius: 0,
                    // По большей стороне — иначе на узком телефоне виньетка
                    // выходит эллипсом и «сдавливает» кадр по бокам.
                    endRadius: max(size.width, size.height) * 0.78
                )

                // 5. Скрим под формой.
                //
                // Мозаика ДВИЖЕТСЯ, а значит яркость под любым текстом — вещь
                // непредсказуемая: сейчас под кнопкой тёмный кадр, через минуту
                // светлый со засветом. Контраст, который «выглядит нормально»
                // на одном кадре, ломается на другом.
                //
                // Скрим убирает саму зависимость: нижние две трети экрана, где
                // живут поля, кнопка и юридический футер, гарантированно
                // затемнены, поэтому 4.5:1 держится при любом положении сетки.
                // Верх остаётся открытым — там знак, и ему фон нужен.
                LinearGradient(
                    stops: [
                        // Шапка гасится плотно, и это не запас «на всякий
                        // случай»: под знаком и подписью стена обязана быть
                        // тёмной. Когда я ослабил эту зону до 0.34, контраст
                        // подписи упал до 3.5:1 при норме 4.5:1 — измеренно, на
                        // снятом кадре. Стена цветная и местами светлая, так что
                        // «выглядит нормально» тут ничего не значит.
                        .init(color: .black.opacity(0.76), location: 0),
                        .init(color: .black.opacity(0.62), location: 0.30),
                        // Светлое окно — РОВНО между подписью и формой, там где
                        // текста нет вообще. Именно здесь стена показывает цвет,
                        // ради которого всё и делалось.
                        .init(color: .black.opacity(0.24), location: 0.40),
                        .init(color: .black.opacity(0.24), location: 0.52),
                        .init(color: .black.opacity(0.72), location: 0.70),
                        .init(color: .black.opacity(0.78), location: 0.70),
                        .init(color: .black.opacity(0.92), location: 1),
                    ],
                    startPoint: .top,
                    endPoint: .bottom
                )

                // 6. Зерно плёнки.
                if !reduceTransparency {
                    FilmGrain()
                        .blendMode(.overlay)
                        .opacity(0.20)
                }
            }
            .ignoresSafeArea()
        }
        .ignoresSafeArea()
        .accessibilityHidden(true)
        .allowsHitTesting(false)
    }
}

// MARK: - Стена афиш

/// Стена киноафиш за формой: СОБСТВЕННЫЕ постеры, современные и насыщенные,
/// разложенные сеткой ПО ДИАГОНАЛИ.
///
/// ПУТЬ К ЭТОМУ СЛОЮ (четыре подхода)
///
/// 1. Генеративная «сетка постеров»: одинаковые прямоугольники 2:3 со сдвигом
///    ряда на половину ширины. Прочли как КИРПИЧНУЮ КЛАДКУ — и справедливо:
///    ряды одинаковых блоков со сдвигом на полблока это и есть кирпичная
///    перевязка. Постер узнаётся по СОДЕРЖИМОМУ, а его в генерации не было.
/// 2. Нарисованный зал с креслами. Кладку убрал, но кресла, нарисованные
///    кодом, читались дешёвой машинной графикой.
/// 3. Настоящие афиши 1925–1929 (общественное достояние). Юридически чисто и
///    фактура настоящая, но прочли как АРХИВ: продукт современный, а на входе
///    его встречало столетнее кино в тёплом монотоне. Справедливо.
/// 4. Собственные постеры (здесь). Насыщенные, с вёрсткой настоящей афиши, по
///    диагонали.
///
/// ПОЧЕМУ НЕ ПОСТЕРЫ NETFLIX, ХОТЯ ХОТЕЛОСЬ ИМЕННО ИХ
///
/// Просьба была прямая: настоящие превью фильмов, как у Netflix. Это единственная
/// часть, которую выполнить нельзя, и причина не в осторожности:
///
///   • постер современного фильма — объект авторского права студии, а
///     декоративный фон в чужом приложении не fair use: использование
///     коммерческое и не трансформирующее;
///   • App Review 5.2 требует, чтобы приложение подавала сторона, которой права
///     принадлежат или лицензированы. Netflix показывает эти постеры, потому что
///     лицензировал сам контент; у Plink такой лицензии нет;
///   • «грузим по сети, не бандлим» — не аргумент: он про распространение, а не
///     про право показывать. Проект этот путь уже проходил (постеры с
///     image.tmdb.org) и откатывал, см. ART_ASSET_LICENSES.md.
///
/// Поэтому афиши свои. Вывод из провала попытки 3: дело было не в том, что
/// рисовать нельзя, а в том, что рисовали ПОД СТАРИНУ и обесцвечивали.
///
/// ЧТО ДЕЛАЕТ ИХ ПОХОЖИМИ НА ПОСТЕРЫ
///
/// Не сюжет, а ВЁРСТКА: крупный титул в нижней трети и россыпь мелких строк под
/// ним. Эту структуру глаз считывает как «афиша» даже там, где текст нечитаем, а
/// на 126 pt под размытием он нечитаем всегда. Плюс своя палитра и свой сюжет из
/// восьми (горизонт, двое в контражуре, туманность, раскол, город, скорость,
/// портал, волна) — постер узнаётся по композиции и фокусу.
///
/// Цвет НЕ приглушён. Именно обесцвечивание до тёплого монотона делало прошлую
/// версию архивной; связь с продуктом держат общая глубокая база и единая
/// оптика, а не единый оттенок.
///
/// ЛИКВИД-ГЛАСС ЗАПЕЧЁН В АССЕТ
///
/// У каждой афиши скруглённые углы и стеклянный блик, нарисованные на этапе
/// сборки ассета. Тридцать живых `glassEffect` на фоне стоили бы кадров и ничего
/// не дали бы: стекло на неподвижной подложке читается блеском, а не рефракцией.
/// Живым остаётся только один бегущий отсвет поверх стены — он и даёт ощущение
/// «жидкого» стекла, потому что двигается.
private struct PosterWall: View {
    let size: CGSize
    let t: TimeInterval

    // Геометрия полотна. ДОЛЖНА совпадать с scripts/make_poster_wall.py
    // (PW/PH/COLS/ROWS/GAP): там из этих же чисел собирается ассет. Держим их
    // здесь именованными, а не вписанными в выражение, чтобы при правке сетки
    // было видно, что менять надо в двух местах.
    //
    // Считаем в тех же условных единицах, что скрипт (пиксели исходной сетки),
    // и только потом переводим в ширины афиши: если считать зазор в долях
    // ширины афиши, по вертикали он получится не тот, потому что афиша не
    // квадратная.
    private static let posterW: CGFloat = 300
    private static let posterH: CGFloat = 450
    private static let cols: CGFloat = 6
    private static let rows: CGFloat = 5
    private static let gap: CGFloat = 24

    private static let sheetPixelW = cols * posterW + gap * (cols + 1)
    private static let sheetPixelH = rows * posterH + gap * (rows + 1)

    /// Ширина полотна, выраженная в ширинах одной афиши.
    static let sheetWidthInPosters: CGFloat = sheetPixelW / posterW

    /// Пропорция полотна (ширина / высота).
    static let sheetAspect: CGFloat = sheetPixelW / sheetPixelH

    /// Наклон сетки.
    ///
    /// Ровная сетка читается каталогом: строгие горизонтали и вертикали — это
    /// таблица, а не фон. Наклон превращает её в «стену, снятую под углом»:
    /// линии перестают быть параллельными кромкам экрана, и фон уходит на задний
    /// план сам собой.
    ///
    /// 12° — не «на глаз». Меньше 8° читается как перекос, будто картинку
    /// положили криво; больше 16° — ряды идут почти по диагонали кадра, и глаз
    /// начинает следить за ними вместо формы входа.
    ///
    /// Важно не спутать с той самой «кирпичной кладкой»: кладку давал сдвиг ряда
    /// на ПОЛБЛОКА (перевязка). Наклон ровной сетки перевязки не создаёт — ряды
    /// остаются рядами, просто идут по диагонали.
    ///
    /// ПОКРЫТИЕ. После поворота на α прямоугольный экран w×h вписывается в
    /// w·cos α + h·sin α по ширине и w·sin α + h·cos α по высоте; к этому надо
    /// добавить обе амплитуды панорамы. На iPhone 393×852 это 601×949 pt, а
    /// полотно при `posterWidthFraction` 0.32 выходит 825×1004 pt — покрывает с
    /// запасом, и в углу не появляется пустой треугольник (самый заметный из
    /// возможных дефектов фона). Проверено и на 320×568, и на 440×956.
    /// Уменьшать `posterWidthFraction` без пересчёта этого неравенства нельзя.
    private static let tilt: Angle = .degrees(-12)

    /// Ширина одной афиши в долях ширины экрана. См. расчёт покрытия выше.
    private static let posterWidthFraction: CGFloat = 0.32

    var body: some View {
        // Панорама: очень медленный сдвиг, как будто камера едет по стене.
        let driftX = CGFloat(sin(t * 0.013)) * size.width * 0.05
        let driftY = CGFloat(cos(t * 0.009)) * size.height * 0.02

        // В кадр попадает примерно три афиши по горизонтали.
        //
        // Первая попытка растягивала ассет на 1.5 экрана целиком (.fill), и в
        // кадр попадало две-три афиши: они выходили размером в пол-экрана,
        // читались размытыми пятнами, и вся затея с постерами теряла смысл —
        // постер узнаётся, только когда видно, что это ОДНА ИЗ МНОГИХ афиш на
        // стене.
        let posterW = size.width * PosterWall.posterWidthFraction
        // Полотно — сетка 6×5 афиш 2:3 с зазорами в 8% ширины афиши, то есть
        // 6 афиш + 7 зазоров по горизонтали. Отсюда и множитель, и пропорция:
        // обе величины выведены из геометрии сетки, а не подобраны на глаз,
        // поэтому афиши не растягиваются (см. scripts/make_poster_wall.py —
        // размеры экспорта там тоже считаются от пропорции полотна).
        let sheetW = posterW * PosterWall.sheetWidthInPosters
        let sheetH = sheetW / PosterWall.sheetAspect

        return ZStack {
            Image("AuthPosterWall")
                .resizable()
                .frame(width: sheetW, height: sheetH)
                .offset(x: driftX, y: driftY)
                // Размытие небольшое и привязано к размеру афиши: афиши должны
                // остаться афишами. При сильном размытии они снова превращаются
                // в однородные пятна, то есть в ту же кладку, от которой ушли.
                .blur(radius: posterW * 0.022)

            // Бегущий отсвет — единственная живая часть стекла.
            //
            // Блик на каждой афише запечён в ассет и потому неподвижен; сам по
            // себе он даёт «глянец», но не «жидкость». Эта широкая полоса идёт
            // поперёк стены по своему циклу и, проходя по запечённым бликам,
            // заставляет их вспыхивать по очереди. Отсюда ощущение текущего
            // стекла — при том что перерисовывается один градиент, а не
            // тридцать стеклянных поверхностей.
            LinearGradient(
                stops: [
                    .init(color: .clear, location: 0),
                    .init(color: .white.opacity(0.05), location: 0.42),
                    .init(color: .white.opacity(0.13), location: 0.5),
                    .init(color: .white.opacity(0.05), location: 0.58),
                    .init(color: .clear, location: 1),
                ],
                startPoint: .topLeading,
                endPoint: .bottomTrailing
            )
            .frame(width: sheetW, height: sheetH)
            // Период ~47 с: заметно быстрее панорамы (та идёт восемь минут), но
            // всё ещё медленно — отсвет должен проплывать, а не мигать.
            .offset(
                x: CGFloat(sin(t * 0.133)) * size.width * 0.9,
                y: CGFloat(cos(t * 0.101)) * size.height * 0.4
            )
            .blendMode(.plusLighter)
            .allowsHitTesting(false)
        }
        // Поворот ПОСЛЕ сборки обоих слоёв, чтобы отсвет наклонился вместе со
        // стеной: иначе он шёл бы по своим осям и читался бы бликом на стекле
        // самого телефона, а не на афишах.
        //
        // Промежуточной рамки здесь нет намеренно: полотно уже больше того, что
        // требуется после поворота (см. расчёт у `tilt`), и лишняя рамка только
        // создавала бы впечатление, будто покрытие обеспечивает она.
        .rotationEffect(PosterWall.tilt)
        .frame(width: size.width, height: size.height)
        .clipped()
        // Стена — подложка, а не картинка. При полной непрозрачности афиши
        // спорили с бренд-блоком: глаз шёл читать постеры, а не название
        // приложения. Стало чуть плотнее прежних 0.55: цвет теперь насыщенный,
        // и при 0.55 от него оставалась муть.
        .opacity(0.62)
        .allowsHitTesting(false)
    }
}

// MARK: - Луч проектора

/// Луч из-за верхней кромки экрана. Мотивирует свет: знак и главная кнопка
/// светлые не «просто так», а потому что на них падает луч.
private struct ProjectorBeam: View {
    let size: CGSize

    var body: some View {
        let apexX = size.width * 0.5
        let topY: CGFloat = -80
        let bottomY = size.height * 0.62

        var cone = Path()
        cone.move(to: CGPoint(x: apexX - 14, y: topY))
        cone.addLine(to: CGPoint(x: apexX + 14, y: topY))
        cone.addLine(to: CGPoint(x: apexX + size.width * 0.42, y: bottomY))
        cone.addLine(to: CGPoint(x: apexX - size.width * 0.42, y: bottomY))
        cone.closeSubpath()

        return ZStack {
            cone.fill(
                LinearGradient(
                    stops: [
                        // Тёплый, а не белый: луч и свет знака — один источник.
                        .init(color: PlinkTheatre.warm.opacity(0.10), location: 0),
                        .init(color: PlinkTheatre.warm.opacity(0.035), location: 0.5),
                        .init(color: .clear, location: 1),
                    ],
                    startPoint: .top,
                    endPoint: .bottom
                )
            )
            .blur(radius: 30)
            .blendMode(.screen)

            // Свечение «объектива» у источника.
            Circle()
                .fill(PlinkTheatre.warm.opacity(0.14))
                .frame(width: 76, height: 76)
                .blur(radius: 36)
                .position(x: apexX, y: topY + 34)
                .blendMode(.screen)
        }
        .allowsHitTesting(false)
    }
}

// MARK: - Зерно плёнки

/// Зерно — самый дешёвый по цене и самый заметный по эффекту слой: он убирает
/// «пластиковость» ровных градиентов и полосы бандинга на тёмном.
///
/// Рисуется ОДИН раз в статичную картинку и не анимируется: живое зерно на
/// каждом кадре — это перерисовка всего экрана 60 раз в секунду ради эффекта,
/// который человек на экране входа не заметит, зато заметит по нагреву.
private struct FilmGrain: View {
    var body: some View {
        Image(uiImage: Self.tile)
            .resizable(resizingMode: .tile)
            .allowsHitTesting(false)
    }

    /// Тайл 128×128. Сид фиксированный — снапшот-тесты не должны мигать.
    private static let tile: UIImage = {
        let side = 128
        var pixels = [UInt8](repeating: 0, count: side * side * 4)
        var state: UInt64 = 0x9E3779B97F4A7C15

        for i in 0..<(side * side) {
            // xorshift: детерминированно и без Foundation-рандома.
            state ^= state << 13
            state ^= state >> 7
            state ^= state << 17
            let v = UInt8(truncatingIfNeeded: state >> 24)
            // Серое вокруг средней точки: в .overlay это и осветляет, и
            // затемняет, то есть работает как зерно, а не как «шум сверху».
            let g = 108 + UInt8(Double(v) * 0.16)
            let o = i * 4
            pixels[o] = g
            pixels[o + 1] = g
            pixels[o + 2] = g
            pixels[o + 3] = 255
        }

        let cs = CGColorSpaceCreateDeviceRGB()
        guard let provider = CGDataProvider(data: Data(pixels) as CFData),
              let cg = CGImage(
                width: side, height: side,
                bitsPerComponent: 8, bitsPerPixel: 32,
                bytesPerRow: side * 4,
                space: cs,
                bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.premultipliedLast.rawValue),
                provider: provider, decode: nil,
                shouldInterpolate: false, intent: .defaultIntent
              )
        else { return UIImage() }
        return UIImage(cgImage: cg)
    }()
}
